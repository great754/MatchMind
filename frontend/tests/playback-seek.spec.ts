import {test,expect} from '@playwright/test';
import {writeFile} from 'node:fs/promises';
import {getPlaybackAnchorTime,getPlaybackSeekTime} from '../../src/serving/static/playback.js';
import {preciseTime,eventLabel} from '../src/time';
import type {Event} from '../src/contracts';
test('real Azure event lead-in, watching through action, Ask followup and report deep link',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const response=await page.request.get('/api/matches/132877_clip/view');expect(response.ok()).toBe(true);
 const view=await response.json();const events:Event[]=view.events;const fps=view.replay.fps;
 const transfers=events.filter(e=>e.type==='PASS_COMPLETED'&&typeof e.metrics.start_frame==='number'&&e.timestamp>5).slice(0,3);
 const tactical=events.find(e=>e.source==='tactical_state_engine'&&typeof e.tactical?.evidence_start_frame==='number'&&e.timestamp>5)!;
 const shot=events.find(e=>e.type==='SHOT_CANDIDATE')!;
 expect(transfers).toHaveLength(3);expect(tactical).toBeTruthy();expect(shot).toBeTruthy();
 const examples=[...transfers,tactical,shot];const results:unknown[]=[];
 await page.goto('/');await page.getByLabel('Recording',{exact:true}).selectOption('132877_clip');
 await expect(page.getByText('API connected')).toBeVisible();
 if(await page.getByRole('dialog').isVisible())await page.getByRole('button',{name:'Use neutral labels'}).click();
 await page.getByLabel('Answer provider').selectOption('local');
 await page.getByLabel('Filter timeline').selectOption('all');
 const video=page.locator('video');await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.readyState),{timeout:45000}).toBeGreaterThanOrEqual(2);
 for(const event of examples){
  await page.getByLabel('Filter timeline').selectOption(event.source==='transfer'?'transfers':event.source==='trajectory'?'shots':'shape');
  const seek=getPlaybackSeekTime(event.timestamp,event,fps,(view.replay.frames-1)/fps);
  const marker=page.getByRole('button',{name:`${eventLabel(event)} at ${preciseTime(event.timestamp)}`,exact:true});
  // A group can select a more significant subtype in the timeline; select its category representative.
  const representative=events.filter(e=>e.group_id===event.group_id).sort((a,b)=>b.significance-a.significance)[0];
  const button=await marker.count()?marker:page.getByRole('button',{name:`${eventLabel(representative)} at ${preciseTime(representative.timestamp)}`,exact:true});
  const left=await button.evaluate(e=>(e as HTMLElement).style.left);
  await button.click();
  await expect(page.getByTestId('current-time')).toHaveText(preciseTime(seek));
  await expect(page.getByRole('img',{name:`Tactical pitch at ${seek.toFixed(2)} seconds`})).toBeVisible();
  await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.seeking),{timeout:30000}).toBe(false);
  expect(await video.evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeCloseTo(seek,1);
  expect(await button.evaluate(e=>(e as HTMLElement).style.left)).toBe(left);
  expect(seek).toBeLessThanOrEqual(getPlaybackAnchorTime(event.timestamp,event,fps));
  await page.screenshot({path:`test-results/playback-${event.event_id}-before.png`,fullPage:true});
  await video.screenshot({path:`test-results/playback-${event.event_id}-video-before.png`});
  await video.evaluate((v:HTMLVideoElement)=>{v.playbackRate=4;return v.play()});
  await expect.poll(()=>video.evaluate((v:HTMLVideoElement)=>v.currentTime),{timeout:20000}).toBeGreaterThan(event.timestamp+.2);
  await video.evaluate((v:HTMLVideoElement)=>{v.pause();v.playbackRate=1});
  await page.screenshot({path:`test-results/playback-${event.event_id}-after.png`,fullPage:true});
  await video.screenshot({path:`test-results/playback-${event.event_id}-video-after.png`});
  results.push({recording_id:'132877_clip',event_id:event.event_id,type:event.type,canonical:event.timestamp,start:getPlaybackAnchorTime(event.timestamp,event,fps),end:typeof event.metrics.end_frame==='number'?event.metrics.end_frame/fps:null,published:event.timestamp,seek,video_played_past_event:true});
 }
 await page.getByRole('button',{name:'Show the most difficult completed transfer.'}).click();
 await expect(page.getByText('Looking up grounded match evidence…')).not.toBeVisible();
 await page.getByRole('button',{name:'Jump to moment',exact:false}).last().click();
 const before=await page.getByTestId('current-time').textContent();
 await page.getByLabel('Ask about this match').fill('Take me there');await page.getByRole('button',{name:'Ask TactiqAI',exact:true}).click();
 await expect(page.getByText('Looking up grounded match evidence…')).not.toBeVisible();
 await expect(page.getByTestId('current-time')).toHaveText(before!);
 await page.getByLabel('Recording',{exact:true}).selectOption('128058_clip');
 await expect(page.getByText('API connected')).toBeVisible();
 await expect.poll(async()=>Number(await page.getByRole('slider',{name:'Match timestamp'}).inputValue())).toBeLessThanOrEqual(1/fps);
 await page.getByLabel('Recording',{exact:true}).selectOption('132877_clip');
 await expect(page.getByText('API connected')).toBeVisible();
 await expect.poll(async()=>Number(await page.getByRole('slider',{name:'Match timestamp'}).inputValue())).toBeLessThanOrEqual(1/fps);
 const e=transfers[0];
 await page.goto(`/api/matches/132877_clip/report?t=${e.timestamp}&event_id=${e.event_id}`);
 await expect.poll(async()=>Number(await page.locator('#time').inputValue())).toBeCloseTo(getPlaybackSeekTime(e.timestamp,e,fps,(view.replay.frames-1)/fps),5);
 await writeFile('test-results/playback-real-events.json',JSON.stringify(results,null,2));
 expect(errors).toEqual([]);
});
